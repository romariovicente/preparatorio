"""Verify the corrected original rig and hide only its inverted outline shells.

The prior master and source GLB are preserved. This operates on already assembled
scenes rather than recreating or clearing the user's project.
"""
import bpy, json, re, math, shutil
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
master = ROOT / 'art/blender/PREPARATORIO_PROJETO_20261002.blend'
backup = ROOT / 'art/blender/checkpoints/PREPARATORIO_PROJETO_20261002_BEFORE_COLOR_QA.blend'
if master.exists() and not backup.exists():
    shutil.copy2(master, backup)
audit_path = ROOT / 'reports/material_qa/anime_color_fix.json'
audit = json.loads(audit_path.read_text(encoding='utf-8'))
scene = bpy.data.scenes.new('VALIDATE_COLOR_QA')
bpy.context.window.scene = scene
bpy.ops.import_scene.gltf(filepath=audit['output'])
meshes = [o for o in scene.objects if o.type == 'MESH']
arms = [o for o in scene.objects if o.type == 'ARMATURE']
triangles = sum(sum(len(p.vertices)-2 for p in o.data.polygons) for o in meshes)
assert len(meshes) == 12 and triangles == 29611, (len(meshes), triangles)
assert len(arms) == 1 and len(arms[0].data.bones) == 145
assert all(any(m.type == 'ARMATURE' for m in o.modifiers) for o in meshes)
assert all(math.isfinite(x) for o in meshes for v in o.data.vertices for x in v.co)
clips = [t.name for t in arms[0].animation_data.nla_tracks]
assert any(n.endswith('Walk') for n in clips) and any(n.endswith('Idle') for n in clips), clips
audit['blenderReimport'] = {'version': bpy.app.version_string, 'meshes': len(meshes), 'triangles': triangles, 'bones': 145, 'clips': clips, 'finiteVertices': True}
audit['blenderReimportValidated'] = True

# The expanded black inverted meshes are separate authored outline shells.
# Hide them in copies of this specific character; leave all buffers and the
# original source in place for recovering the original toon rendering.
toon = {'BootsToon','HairToon','ImplantToon','PantsToon','PouchToon','Toon','BodyToon'}
hidden = []
for root in list(bpy.data.objects):
    if root.get('source_id') != audit['id']:
        continue
    for obj in root.children_recursive:
        if obj.type != 'MESH' or not obj.data.materials:
            continue
        names = [re.sub(r'\.\d+$', '', m.name) for m in obj.data.materials if m]
        if names and all(name in toon for name in names):
            obj.hide_render = True
            obj.hide_viewport = True
            obj['color_qa'] = 'Original inverted toon outline shell hidden; source retained'
            hidden.append(obj.name)
assert len(hidden) >= 18, hidden
audit['blenderHiddenShells'] = hidden
audit_path.write_text(json.dumps(audit, ensure_ascii=False, indent=2), encoding='utf-8')

# The validation scenes are generated by these scripts, not supplied progress.
for generated in ['VALIDATE_COLOR_QA','VALIDATE_CAMPUS_V2']:
    validation = bpy.data.scenes.get(generated)
    if validation:
        objects = list(validation.objects)
        bpy.data.scenes.remove(validation)
        for obj in objects:
            if not obj.users_scene:
                bpy.data.objects.remove(obj, do_unlink=True)

gallery = bpy.data.scenes['ACERVO_PERSONAGENS']
bpy.context.window.scene = gallery
gallery.frame_set(1)
gallery.render.filepath = str(ROOT / 'reports/ACERVO_Personagens.png')
bpy.ops.render.render(write_still=True)
bpy.data.libraries.write(str(ROOT / 'art/blender/ACERVO_Personagens_20261002.blend'), {gallery}, fake_user=True, compress=True)
main = bpy.data.scenes['00_PREP_CAMPUS']
bpy.context.window.scene = main
main.frame_set(1)
main.render.filepath = str(ROOT / 'reports/PREP_CAMPUS_20261002.png')
bpy.ops.render.render(write_still=True)
for screen in bpy.data.screens:
    for area in screen.areas:
        if area.type == 'VIEW_3D':
            area.spaces.active.shading.type = 'MATERIAL'
            area.spaces.active.region_3d.view_perspective = 'CAMERA'
            area.spaces.active.overlay.show_overlays = False
        if area.type == 'VIEW_3D':
            area.spaces.active.shading.color_type = 'MATERIAL'
for scene in bpy.data.scenes:
    if scene.name == '00_PREP_CAMPUS' or scene.name.startswith(('ACERVO_', 'PREP_')):
        scene.unit_settings.system = 'METRIC'
        scene.unit_settings.scale_length = 1
        scene.tool_settings.snap_elements = {'INCREMENT'}
        if hasattr(scene.tool_settings, 'use_snap_grid_absolute'):
            scene.tool_settings.use_snap_grid_absolute = True
bpy.ops.wm.save_as_mainfile(filepath=str(master), compress=True)

record_path = ROOT / 'reports/supplied/SUP_lowpoly_anime_character_cyberstyle.json'
record = json.loads(record_path.read_text(encoding='utf-8'))
record.update(url=audit['url'], sha256=audit['sha256'], bytes=audit['bytes'], triangles=triangles, meshes=len(meshes))
if audit['modification'] not in record['modifications']:
    record['modifications'] += ' ' + audit['modification']
record['validation'] += '; Color_v2 Blender reimport: 12 active meshes, 29611 active triangles, 145 bones, Idle/Walk retained'
record_path.write_text(json.dumps(record, ensure_ascii=False, indent=2), encoding='utf-8')
report_path = ROOT / 'reports/blender_expansion_validation.json'
report = json.loads(report_path.read_text(encoding='utf-8'))
report.update(scenes=[s.name for s in bpy.data.scenes], activeScene=bpy.context.scene.name, materials=len(bpy.data.materials), objects=len(bpy.data.objects), armatures=len(bpy.data.armatures), packedImages=sum(bool(i.packed_file) for i in bpy.data.images), colorReimportValidated=True, hiddenToonShells=len(hidden), bytes=master.stat().st_size)
report_path.write_text(json.dumps(report, ensure_ascii=False, indent=2), encoding='utf-8')
print(json.dumps({'colorQA': audit['blenderReimport'], 'hiddenShells': len(hidden), 'blend': str(master), 'bytes': master.stat().st_size}))
